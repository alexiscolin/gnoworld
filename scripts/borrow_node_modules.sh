#!/bin/sh
# borrow_node_modules.sh <copy>: a copy of the repository without installed packages (the
# pre-commit's staged files, a worktree) borrows the working tree's, at the same paths. The root's,
# pnpm's store, is linked; a workspace's is copied as its links, so its link to a workspace package
# (app's @gnoworld/ui) leads to the copy's own, not the working tree's (F344). A workspace's .bin is the copy's own
# folder, even where it is a link: the probe deletes a tool in its copy, which went through a linked .bin (F2127). A StrykerJS
# sandbox in .stryker-tmp is none of the packages: the copy has none of it (F2414: a copy's lint once reported 14683 problems).
# worktree.sh runs it outside the sandbox (F5099), so find hands each folder's name whole to the loop: read line by line, a name
# holding a newline split into paths of their own, and `a<newline>..` led its copies out of the copy. The loop writes through no
# link already standing on the way to <copy>/<folder>, which the copy's tree checked out (a node_modules tracked as a link
# included); it copies a linked .bin's files from a node_modules/.bin alone, which could otherwise be what the session cannot
# read: the folder the link led to when read, whole, never through the link again (cp -P copies a link as one).
set -eu
find . -name node_modules -type d -prune -not -path './.git/*' -not -path './.claude/*' -not -path './.stryker-tmp/*' -exec sh -c '
set -eu
copy=$1
shift
unlinked() { # whether the folders on the way to $copy/$1 that stand are folders, never links
	p=$copy rest=${1#./}
	while [ -n "$rest" ]; do
		p=$p/${rest%%/*}
		case $rest in */*) rest=${rest#*/} ;; *) rest= ;; esac
		[ ! -L "$p" ] || return 1
		[ -e "$p" ] || return 0
	done
}
for m; do
	unlinked "$m" || { echo "borrow_node_modules.sh: $copy/$m leads through a link" >&2; exit 1; }
	mkdir -p "$copy/$(dirname "$m")"
	if [ "$m" = ./node_modules ]; then ln -s "$PWD/$m" "$copy/$m"; else cp -RP "$m" "$copy/$m"; fi
	if [ "$m" != ./node_modules ] && [ -L "$copy/$m/.bin" ]; then
		bin=$(cd "$m/.bin" && pwd -P)
		case $bin in */node_modules/.bin) ;; *) echo "borrow_node_modules.sh: $m/.bin leads elsewhere than a node_modules/.bin" >&2; exit 1 ;; esac
		rm "$copy/$m/.bin" && cp -RP "$bin" "$copy/$m/.bin"
	fi
done' sh "$1" {} +
