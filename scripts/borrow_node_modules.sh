#!/bin/sh
# borrow_node_modules.sh <copy>: a copy of the repository without installed packages (the
# pre-commit's staged files, a worktree) borrows the working tree's, at the same paths. The root's,
# pnpm's store, is linked; a workspace's is copied as its links, so its link to a workspace package
# (app's @gnoworld/ui) leads to the copy's own, not the working tree's (F344). A workspace's .bin is the copy's own
# folder, even where it is a link: the probe deletes a tool in its copy, which went through a linked .bin (F2127).
set -eu
find . -name node_modules -type d -prune -not -path './.git/*' -not -path './.claude/*' | while read -r m; do
	mkdir -p "$1/$(dirname "$m")"
	if [ "$m" = ./node_modules ]; then ln -s "$PWD/$m" "$1/$m"; else cp -RP "$m" "$1/$m"; fi
	if [ "$m" != ./node_modules ] && [ -L "$1/$m/.bin" ]; then
		rm "$1/$m/.bin" && mkdir "$1/$m/.bin" && cp -RP "$m/.bin/." "$1/$m/.bin/"
	fi
done
