// Command sealvec is the reference client for r/seal's signing formats. It builds
// a 3-message transcript, its Merkle root (tm2 simple Merkle, the tree that
// crypto/merkle verifies in the VM), and the Bind/Seal signatures for
// deterministic test keys, with seals each test can make on its own (a page of
// eleven, a seal of two messages). It prints them as the realm tests' vectors file:
//
//	go run ./tools/sealvec > r/seal/vectors_test.gno
//
// The gate (scripts/check.sh) fails when that file differs from this output.
package main

import (
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"encoding/hex"
	"flag"
	"fmt"
	"sort"
	"strconv"
)

func main() {
	chain := flag.String("chain", "dev", "chain id")
	realm := flag.String("realm", "gno.land/r/gnoworld/seal", "realm path")
	addrA := flag.String("a", "g1jg8mtutu9khhfwc4nxmuhcpftf0pajdhfvsqf5", "alice's address, for her Bind")
	addrB := flag.String("b", "g1y2tswmrtlany2ffmpyc0uyunk4gt4gv8gtf736", "bob's address, for his Bind")
	flag.Parse()

	alice, bob := key("alice"), key("bob")
	pubA, pubB := alice.Public().(ed25519.PublicKey), bob.Public().(ed25519.PublicKey)

	// Each leaf: salt(32) | sender key(32) | seq(8, BE) | previous leaf hash(32) | plaintext.
	texts := []string{"see you at 6pm?", "ok, in front of the station", "deal"}
	senders := []ed25519.PublicKey{pubA, pubB, pubA}
	var leaves [][]byte
	prev := make([]byte, 32)
	for i, t := range texts {
		salt := sha256.Sum256([]byte("salt" + strconv.Itoa(i)))
		leaf := append(append(salt[:], senders[i]...), binary.BigEndian.AppendUint64(nil, uint64(i))...)
		leaf = append(append(leaf, prev...), t...)
		leaves = append(leaves, leaf)
		prev = leafHash(leaf)
	}
	root := merkleRoot(leaves)
	var aunts []byte
	for _, a := range proof(leaves, 1) {
		aunts = append(aunts, a...)
	}

	prefix := func(kind string) string { return "gnoworld/" + kind + "/v1|" + *chain + "|" + *realm + "|" }
	// The seal statement names both keys, smaller first; Seal enforces that order.
	sealMsg := func(r []byte, x, y ed25519.PublicKey, n int) []byte {
		if string(x) > string(y) {
			x, y = y, x
		}
		return []byte(prefix("seal") + string(r) + string(x) + string(y) + "|" + strconv.Itoa(n))
	}
	carol, alice2 := key("carol"), key("alice2")
	pubC, pubA2 := carol.Public().(ed25519.PublicKey), alice2.Public().(ed25519.PublicKey)

	b64 := base64.StdEncoding.EncodeToString
	// pair seals r, n messages, by two keys of its own that no address binds: {a, b, sigA, sigB}, a < b, and a's private key.
	pair := func(r []byte, name string, n int) ([4]string, ed25519.PrivateKey) {
		x, y := key(name+" x"), key(name+" y")
		px, py := x.Public().(ed25519.PublicKey), y.Public().(ed25519.PublicKey)
		if string(px) > string(py) {
			x, y, px, py = y, x, py, px
		}
		msg := sealMsg(r, px, py, n)
		return [4]string{b64(px), b64(py), b64(ed25519.Sign(x, msg)), b64(ed25519.Sign(y, msg))}, x
	}
	// Eleven seals of a root of their own, one message each, sorted by key a, the order Render lists them in: it shows ten.
	// page[0]'s key a, listed first, has a Bind to bob's address, so Render shows one key by its address.
	pageRoot := sha256.Sum256([]byte("gnoworld test page root"))
	type sealed struct {
		v [4]string
		a ed25519.PrivateKey
	}
	var page []sealed
	for i := range 11 {
		v, a := pair(pageRoot[:], "page "+strconv.Itoa(i), 1)
		page = append(page, sealed{v, a})
	}
	pub := func(k ed25519.PrivateKey) string { return string(k.Public().(ed25519.PublicKey)) } // bytes: Render orders keys by their hex
	sort.Slice(page, func(i, j int) bool { return pub(page[i].a) < pub(page[j].a) })
	two, _ := pair(root, "two", 2)

	out := [][2]string{
		{"pubA", b64(pubA)}, {"pubB", b64(pubB)}, {"pubC", b64(pubC)}, {"pubA2", b64(pubA2)},
		{"root", b64(root)},
		{"sealSigA", b64(ed25519.Sign(alice, sealMsg(root, pubA, pubB, len(leaves))))}, {"sealSigB", b64(ed25519.Sign(bob, sealMsg(root, pubA, pubB, len(leaves))))},
		{"spliceSigC", b64(ed25519.Sign(carol, sealMsg(root, pubA, pubC, len(leaves))))}, // carol's half of a forged alice+carol seal
		{"bindSigA", b64(ed25519.Sign(alice, []byte(prefix("bind")+*addrA)))},
		{"bindSigA2", b64(ed25519.Sign(alice2, []byte(prefix("bind")+*addrA)))}, // alice rotates to a new key
		{"bindSigB", b64(ed25519.Sign(bob, []byte(prefix("bind")+*addrB)))},
		{"leaf0", b64(leaves[0])}, {"leaf1", b64(leaves[1])}, {"leaf2", b64(leaves[2])},
		{"aunts1", b64(aunts)}, {"rootHex", hex.EncodeToString(root)},
		{"pageRoot", b64(pageRoot[:])}, {"pageRootHex", hex.EncodeToString(pageRoot[:])},
		{"pageBindSig", b64(ed25519.Sign(page[0].a, []byte(prefix("bind")+*addrB)))},
	}

	fmt.Print("// Code generated by tools/sealvec; DO NOT EDIT.\n\npackage seal\n\nconst (\n")
	fmt.Printf("\talice = address(%q)\n\tbob = address(%q)\n\tnLeaves = %d\n", *addrA, *addrB, len(leaves))
	for _, kv := range out {
		fmt.Printf("\t%s = %q\n", kv[0], kv[1])
	}
	fmt.Print(")\n\n// Seals of pageRoot with n = 1, each {a, b, sigA, sigB}, a < b, sorted by a; pageBindSig binds page[0]'s a to bob.\nvar page = [...][4]string{\n")
	for _, p := range page {
		fmt.Printf("\t{%q, %q, %q, %q},\n", p.v[0], p.v[1], p.v[2], p.v[3])
	}
	fmt.Printf("}\n\n// A seal of root with n = 2, {a, b, sigA, sigB}, a < b; neither key is bound.\nvar sealOfTwo = [4]string{%q, %q, %q, %q}\n", two[0], two[1], two[2], two[3])
}

// key derives a deterministic test key. Real clients use ed25519.GenerateKey.
func key(name string) ed25519.PrivateKey {
	seed := sha256.Sum256([]byte("gnoworld test " + name))
	return ed25519.NewKeyFromSeed(seed[:])
}

func leafHash(b []byte) []byte { h := sha256.Sum256(append([]byte{0}, b...)); return h[:] }

func innerHash(l, r []byte) []byte {
	h := sha256.Sum256(append(append([]byte{1}, l...), r...))
	return h[:]
}

// split is tm2's: the largest power of two strictly below n.
func split(n int) int {
	k := 1
	for k*2 < n {
		k *= 2
	}
	return k
}

func merkleRoot(items [][]byte) []byte {
	if len(items) == 1 {
		return leafHash(items[0])
	}
	k := split(len(items))
	return innerHash(merkleRoot(items[:k]), merkleRoot(items[k:]))
}

// proof returns item i's aunts, leaf to root, as crypto/merkle.VerifySimpleProof wants them.
func proof(items [][]byte, i int) [][]byte {
	if len(items) == 1 {
		return nil
	}
	k := split(len(items))
	if i < k {
		return append(proof(items[:k], i), merkleRoot(items[k:]))
	}
	return append(proof(items[k:], i-k), merkleRoot(items[:k]))
}
